'use strict';
const assert=require('assert/strict'), fs=require('fs'), os=require('os'), path=require('path');
const F=require('../lib/fonti'), G=require('../App/assets/fonti/gruppi');
assert.equal(F.nomeDestinazione('01.1 CT Alunno.pdf',1),'0001 - 01.1 CT Alunno.pdf');
assert.equal(F.nomeDestinazione('12_appunti  à.PDF',42),'0042 - 12_appunti  à.PDF');
assert.equal(F.prossimoNumero(['0009 - 01.1 CT Alunno.pdf','02 vecchio.pdf']),10);
assert.equal(F.prossimoNumero(['9999 - x.pdf']),10000);
const N=require('../App/assets/fonti/nomi');
assert.equal(N.visibile('0001 - 01.1 CT Alunno.pdf'),'01.1 CT Alunno.pdf');
assert.equal(N.visibile('0001 - 0002 - 01.1 CT Alunno.pdf'),'0002 - 01.1 CT Alunno.pdf');
assert.equal(N.visibile('01 vecchio.pdf'),'vecchio.pdf');
assert.equal(N.visibile('01.1 CT Alunno.pdf'),'01.1 CT Alunno.pdf');
assert.equal(N.visibile('Una_lettura - completa.pdf'),'Una_lettura - completa.pdf');
assert.equal(N.numero('10000 - x.pdf'),'10000');
let s=G.normalizza(null,['0001 - Zebra.pdf','0002 - Alunno.pdf','0003 - àlbero.pdf']);
s=G.crea(s,'g','Gruppo');
const prima=JSON.stringify(s), files=s.liberi.slice(0,2);
const spostati=G.spostaMolti(s,[files[1],files[0],files[0],'assente'],'g');
assert.equal(JSON.stringify(s),prima);
assert.deepEqual(spostati.gruppi[0].files,files,'selezione multipla segue l’ordine visibile, senza duplicati');
assert.deepEqual(G.spostaMolti(s,files,'inesistente'),s);
s=G.spostaMolti(spostati,[files[1]],'');
assert.deepEqual(s.liberi,['0003 - àlbero.pdf',files[1]]);
const etichette=Object.fromEntries([...s.liberi,...s.gruppi[0].files].map(f=>[f,N.visibile(f)]));
s=G.ordina(s,'az',etichette);
assert.deepEqual(s.liberi,['0003 - àlbero.pdf',files[1]]);
s=G.ordina(s,'za',etichette);
assert.deepEqual(s.liberi,[files[1],'0003 - àlbero.pdf']);
s=G.trascina(s,{file:files[0],files:[files[0],files[1]]},{file:'0003 - àlbero.pdf',gruppo:'',dopo:true});
assert.deepEqual(s.liberi,['0003 - àlbero.pdf',files[0],files[1]]);
assert.deepEqual(s.gruppi[0].files,[]);
assert.deepEqual(G.trascina(s,{file:files[0],files:[files[0],files[1]]},{file:files[1],gruppo:''}),s);
// Import e rinomina reali: il titolo numerato e i rimandi restano collegati.
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'zaino-nomi-'));
try {
  const id=require('../lib/zaini').crea(tmp,'Nomi').id, src=path.join(tmp,'01.1 CT Alunno.pdf');
  fs.writeFileSync(src,'%PDF-1.4 originale');
  const r=F.importa(tmp,id,[src]);assert.equal(r.copiati[0].nome,'0001 - 01.1 CT Alunno.pdf');
  const app=path.join(tmp,'Zaini',id,'APPUNTI');fs.mkdirSync(app,{recursive:true});
  fs.writeFileSync(path.join(app,'Citazione.md'),'[Alunno](pdf:0001#p=1)');
  const rin=F.rinomina(tmp,id,r.copiati[0].nome,'01.2 CT Alunno');
  assert.equal(rin.error,'');assert.equal(rin.nome,'0001 - 01.2 CT Alunno.pdf');
  assert.deepEqual(F.usi(tmp,id,rin.nome).appunti,['Citazione.md']);
  assert.equal(fs.readFileSync(F.percorso(tmp,id,rin.nome),'utf8'),'%PDF-1.4 originale');
  fs.copyFileSync(src,path.join(F.dirPdf(tmp,id),'09 vecchio.pdf'));
  assert.equal(F.rinomina(tmp,id,'09 vecchio.pdf','02.1 Titolo').nome,'09 02.1 Titolo.pdf');
  assert.equal(F.importa(tmp,id,[src]).copiati[0].nome,'0010 - 01.1 CT Alunno.pdf');
  const lungo='01.1 '+ 'Titolo completo '.repeat(9)+'.PDF';
  assert.equal(F.nomeDestinazione(lungo,11),'0011 - '+lungo);
} finally { fs.rmSync(tmp,{recursive:true,force:true}); }
console.log('✓ Nomi originali, quattro cifre, selezione multipla e ordinamento');

'use strict';
const assert=require('node:assert/strict');
const K=require('../App/assets/evidenze/ordine.js');
const S=require('../App/assets/evidenze/strati.js');
const P=require('../App/assets/fonti/pagina.js');
const lista=[{id:'b',exact:'Beta',creato:'2026-10-16T12:00:00Z'},{id:'a',exact:'Alfa',creato:'2026-10-17T12:00:00Z'},{id:'z',exact:'Zeta'}];
assert.deepEqual(K.ordina(lista,{criterio:'alfa',verso:'asc'}).map(x=>x.id),['a','b','z']);
assert.deepEqual(K.ordina(lista,{criterio:'alfa',verso:'desc'}).map(x=>x.id),['z','b','a']);
assert.deepEqual(K.ordina(lista,{criterio:'data',verso:'asc'}).map(x=>x.id),['b','a','z']);
assert.deepEqual(K.ordina(lista,{criterio:'data',verso:'desc'}).map(x=>x.id),['a','b','z']);
assert.deepEqual(lista.map(x=>x.id),['b','a','z']);
assert.equal(K.etichetta({criterio:'alfa',verso:'desc'}),'AZ');
assert.equal(K.etichetta({criterio:'alfa',verso:'asc'}),'ZA');
assert.equal(K.freccia({criterio:'data',verso:'asc'}),'chevron-up');
assert.equal(K.freccia({criterio:'data',verso:'desc'}),'chevron-down');
assert.deepEqual(K.scegli({criterio:'alfa',verso:'desc'},'data'),{criterio:'data',verso:'desc'});
assert.deepEqual(K.scegli({criterio:'data',verso:'desc'},'data'),{criterio:'data',verso:'asc'});
assert.equal(K.data('2026-10-16T12:00:00Z'),'16 ottobre 2026');
assert.equal(K.data('non valida'),'Data di creazione non disponibile');
assert.equal(S.bloccoScrittura({tutte:false},''),'tutte');
assert.equal(S.bloccoScrittura({tutte:true,spenti:['']},''),'strato');
assert.equal(S.bloccoScrittura({tutte:true,spenti:['nascosto']},'nascosto'),'strato');
assert.equal(S.bloccoScrittura({tutte:true,spenti:['altro']},'visibile'),'');
assert.equal(P.etichetta(null,{numPages:0}),'- di -');
assert.equal(P.etichetta(2,{numPages:3}),'2 di 3');
console.log('toolbar-stati: ordinamenti, date, blocco scrittura e contatore vuoto OK');

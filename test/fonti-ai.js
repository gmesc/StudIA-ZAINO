'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const F = require('../lib/fonti-ai');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'zaino-fonti-ai-'));
const dir = path.join(root, 'Zaini', 'prova');
try {
  fs.mkdirSync(path.join(dir, 'MATERIALI'), { recursive: true });
  fs.mkdirSync(path.join(dir, 'APPUNTI'));
  fs.writeFileSync(path.join(dir, '_zaino.md'), '# Prova');
  fs.writeFileSync(path.join(dir, 'MATERIALI', '01 fonte.txt'), 'La fotosintesi usa la luce.');
  fs.writeFileSync(path.join(dir, 'APPUNTI', 'Nota.md'), 'Nota personale');
  const first = F.sincronizza(root, 'prova');
  const source = first.sources.find(s => s.kind === 'testo');
  assert.equal(first.sources.length, 2);
  assert.equal(F.sincronizza(root, 'prova').sources.find(s => s.id === source.id).revision, source.revision);
  fs.renameSync(path.join(dir, source.file), path.join(dir, 'MATERIALI', '02 rinominata.txt'));
  const renamed = F.sincronizza(root, 'prova').sources.find(s => s.id === source.id);
  assert.equal(renamed.file, 'MATERIALI/02 rinominata.txt');
  assert.equal(F.risolvi(root, 'prova', source).status, 'available');
  fs.writeFileSync(path.join(dir, renamed.file), 'La fonte è cambiata.');
  assert.equal(F.risolvi(root, 'prova', source).status, 'changed');
  fs.unlinkSync(path.join(dir, renamed.file));
  assert.equal(F.risolvi(root, 'prova', source).status, 'removed');
  fs.writeFileSync(path.join(dir, renamed.file), 'Una fonte nuova al posto della vecchia.');
  assert.equal(F.risolvi(root, 'prova', source).status, 'removed');
  const fresh = F.sincronizza(root, 'prova').sources.find(s => s.file === renamed.file);
  assert.notEqual(fresh.id, source.id);
  assert.deepEqual(F.ambito({ mode: 'selected', sourceIds: [] }), { mode: 'selected', sourceIds: [], wikipedia: false });
  assert.throws(() => F.ambito({ mode: 'selected', sourceIds: ['../x'] }), /Ambito/);
  assert.throws(() => F.sincronizza(root, '../prova'), /Zaino/);
  fs.symlinkSync('/etc/hosts', path.join(dir, 'MATERIALI', 'esterno.txt'));
  assert(!F.sincronizza(root, 'prova').sources.some(s => s.file.endsWith('esterno.txt')));
  assert(F.sincronizza(root, 'prova').warnings.some(w => /simbolico/.test(w)));
  fs.writeFileSync(path.join(dir, '_fonti-ai.json'), '{rotto');
  assert.throws(() => F.sincronizza(root, 'prova'), /registro|JSON/i);
  console.log('fonti-ai: identità, revisioni, rinomina, sostituzione, ambito e isolamento OK');
} finally { fs.rmSync(root, { recursive: true, force: true }); }

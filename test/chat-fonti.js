'use strict';
const assert = require('node:assert/strict'), fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const C = require('../lib/chat'), F = require('../lib/fonti-ai');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'zaino-chat-fonti-'));
const d = path.join(root, 'Zaini', 'test');
(async () => {
  fs.mkdirSync(path.join(d, 'MATERIALI'), { recursive: true });
  fs.writeFileSync(path.join(d, '_zaino.md'), '# Test');
  fs.writeFileSync(path.join(d, 'MATERIALI', 'uno.txt'), 'Fonte consentita sulla luce.');
  fs.writeFileSync(path.join(d, 'MATERIALI', 'due.txt'), 'Segreto escluso: clorofilla.');
  const inventory = F.sincronizza(root, 'test').sources;
  const one = inventory.find(s => s.file.endsWith('uno.txt'));
  const scope = { mode: 'selected', sourceIds: [one.id], wikipedia: false };
  const session = C.crea(root, 'test', { scope });
  let asked;
  const opts = { rispondi: async o => { asked = o; return { text: 'Spiegazione [S1].' }; } };
  const request = { sessionId: session.id, text: 'luce', provider: 'openai', model: 'finto' };
  const first = await C.invia(root, 'test', request, opts);
  assert(!first.error);
  assert(!JSON.stringify(asked).includes('Segreto escluso'));
  assert.equal(first.context.sources.length, 1);
  assert.equal(first.context.sources[0].sourceId, one.id);
  const answer = first.session.messages.at(-1);
  assert.equal(C.citazione(root, 'test', session.id, answer.id, '[S1]').status, 'available');
  assert.throws(() => C.citazione(root, 'test', session.id, answer.id, '[S2]'), /Citazione/);
  fs.renameSync(path.join(d, one.file), path.join(d, 'MATERIALI', 'rinominata.txt'));
  assert.equal(C.citazione(root, 'test', session.id, answer.id, '[S1]').source.file, 'MATERIALI/rinominata.txt');
  assert.deepEqual(C.leggi(root, 'test', session.id).scope, scope);
  assert.deepEqual(C.ramifica(root, 'test', session.id, answer.id).scope, scope);
  C.salvaAmbito(root, 'test', session.id, { mode: 'selected', sourceIds: [], wikipedia: false });
  const empty = await C.invia(root, 'test', request, opts);
  assert.equal(empty.context.sources.length, 0);
  assert.equal(asked.messages.length, 1, 'il cambio ambito non reinvia risposte basate su fonti escluse');
  assert(!JSON.stringify(asked).includes('Fonte consentita'));
  fs.writeFileSync(path.join(d, 'MATERIALI', 'rinominata.txt'), 'Contenuto cambiato');
  assert.equal(C.citazione(root, 'test', session.id, answer.id, '[S1]').status, 'changed');
  fs.unlinkSync(path.join(d, 'MATERIALI', 'rinominata.txt'));
  assert.equal(C.citazione(root, 'test', session.id, answer.id, '[S1]').status, 'removed');
  console.log('chat-fonti: ambito persistente, esclusioni, citazioni, ramificazione e storia controllata OK');
})().catch(e => { console.error(e); process.exitCode=1; }).finally(() => fs.rmSync(root, { recursive:true, force:true }));
